/* Array -> e uma estrutura de dados que permite armazenar 
           multiplos valores em uma unica variavel
exemplo:
const frutas = ["maça", "banana", "laranja"];

Obs: dentro do array a posicao do laranja vai ser 2, 
      pois a contagem comeca do 0

*/




const frutas = ["maça", "banana", "laranja"];

console.log(frutas[2])


/* pode mudar o valor do array, mesmo sendo const, pois o array e um objeto
exemplo:
frutas[2] = "abacaxi"

*/

frutas[2] = "abacaxi"
console.log(frutas[2])