
// Esse método é usado para juntar dois arrays. Ele não altera os arrays originais,
//  mas cria um novo array com a soma dos dois arrays escolhidos.

const array1 = ['a', 'b', 'c'];
const array2 = ['d', 'e', 'f'];

const array3 = array1.concat(array2);

console.log(array3);
// ['a', 'b', 'c', 'd', 'e', 'f']

